// build-embedded.mjs
// Bundles the static assets (public/, curriculum/, thock/, music/) into a single
// `server/embedded.mjs` so a compiled single-file binary can serve everything
// from memory. Text assets are inlined as strings; binary assets (sound, music)
// are base64-encoded and flagged in `binary`.
//
// Usage: node scripts/build-embedded.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'server', 'embedded.mjs');

const TEXT_DIRS = ['public', 'curriculum'];
const BIN_DIRS = ['thock', 'music'];

function walk(dir, base, into) {
  if (!fs.existsSync(dir)) return;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.') || entry.name.startsWith('_')) continue;
    const full = path.join(dir, entry.name);
    const rel = path.join(base, entry.name).split(path.sep).join('/');
    if (entry.isDirectory()) walk(full, rel, into);
    else into[rel] = full;
  }
}

const files = {};   // rel path -> content (utf8 for text, base64 for binary)
const binary = [];  // rel paths that are base64

for (const d of TEXT_DIRS) {
  const map = {};
  walk(path.join(ROOT, d), d, map);
  for (const [rel, full] of Object.entries(map)) files[rel] = fs.readFileSync(full, 'utf8');
}
for (const d of BIN_DIRS) {
  const map = {};
  walk(path.join(ROOT, d), d, map);
  for (const [rel, full] of Object.entries(map)) {
    files[rel] = fs.readFileSync(full).toString('base64');
    binary.push(rel);
  }
}

const body =
  '// Auto-generated by scripts/build-embedded.mjs — do not edit.\n' +
  `export const EMBEDDED = ${JSON.stringify({ files, binary })};\n`;

fs.writeFileSync(OUT, body);
console.log(
  `embedded ${Object.keys(files).length} files -> ${OUT} ` +
  `(${(fs.statSync(OUT).size / 1024 / 1024).toFixed(1)} MB)`,
);
