// build-curriculum.mjs
// Emits the Odin Trainer curriculum into ../curriculum/ from a hand-curated
// dataset. Each section is a self-contained folder with a single section.json:
//
//   curriculum/<id>/section.json
//     {
//       name, chapter, chapterTitle, order,
//       snippets: [ { instruction, descriptor, target }, ... ]
//     }
//
// Each snippet is a "prompt -> target" drill:
//   instruction  : short natural-language task (shown in the prompt bar)
//   descriptor   : the book's code "shape" hint (shown in the prompt bar)
//   target       : the real, complete Odin to type (graded)
//
// `descriptor` is a proper subset / shape, never identical to `target`, so the
// recall mode gives a hint without handing over the answer. Targets are real
// Odin taken from odinbook chapters 1-5; prose comments and shell commands are
// omitted. Indentation is tabs (the loader expands to 4 spaces for display).
//
// Usage: node scripts/build-curriculum.mjs

