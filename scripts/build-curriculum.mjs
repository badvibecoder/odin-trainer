fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });

let totalSnippets = 0;
for (const [id, group, order, name, snippets] of curriculum) {
  const dir = path.join(OUT, id);
  fs.mkdirSync(dir, { recursive: true });
  const manifest = {
    name: deidentify(name),
    group,
    groupTitle: GROUP_TITLES[group] || 'Other',
    order,
    snippets: snippets.map((s) => {
      const base = deidentify(s.target).replace(/\s+$/g, '');
      const targets = [];
      const seen = new Set();
      for (let i = 0; i < TARGETS_PER_DRILL; i++) {
        const v = varyTarget(base, i);
        if (seen.has(v)) continue; // short snippets may produce fewer distinct variants
        seen.add(v);
        targets.push(v);
      }
      return {
        instruction: genericizeInstruction(deidentify(s.instruction)),
        targets,
      };
    }),
  };
  fs.writeFileSync(path.join(dir, 'section.json'), JSON.stringify(manifest, null, 2) + '\n');
  totalSnippets += snippets.length;
  console.log(`  ${id}  (${snippets.length} snippets)  ${deidentify(name)}`);
}

console.log(`\nwrote ${curriculum.length} sections, ${totalSnippets} snippets -> ${OUT}`);
